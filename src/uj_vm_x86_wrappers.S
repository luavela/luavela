/*
 * This macro does several things:
 * 1) defines a function with custom personality routine for external unwinder
 * 2) saves callee-saved registers since they will be corrupted during exceptions handling
 *    and restores them on interpreter exit
 * 3) creates room for vm_frame structure and sets up proper DWARF entry for canonical
 *    frame address
 * 4) checks that stack has proper alignment (e.g. GCC 9 does not align stack for naked functions)
 *
 * Note that we allocate a little bit more stack space than needed - 168 bytes, while
 * vm_frame struct occupies only 160 bytes, to get proper 16-bytes stack alignment.
 *
 * NB! Function generated by MAKE_VM_ENTRY_FUNC should accept no more than 5 arguments.
 * This rule also applies to entry_func, since MAKE_VM_ENTRY_FUNC will add 6th
 * argument - pointer to vm_frame structure.
 */

#define MAKE_VM_ENTRY_FUNC(func_name, entry_func)     \
    .global #func_name;                               \
#func_name:                                           \
    .cfi_startproc;                                   \
    .cfi_personality 0x1b, uj_dwarf_personality;      \
    test $15,%rsp;                                    \
    jz 1f;                                            \
    /* Properly aligned stack */                      \
    sub $168,%rsp;                                    \
    .cfi_def_cfa_offset 176;                          \
    mov %rbp,136(%rsp);                               \
    mov %rbx,128(%rsp);                               \
    mov %r15,120(%rsp);                               \
    mov %r14,112(%rsp);                               \
    mov %r13,104(%rsp);                               \
    mov %r12,96(%rsp);                                \
    mov %rsp,%r9;                                     \
    call #entry_func;                                 \
    mov 136(%rsp),%rbp;                               \
    mov 128(%rsp),%rbx;                               \
    mov 120(%rsp),%r15;                               \
    mov 112(%rsp),%r14;                               \
    mov 104(%rsp),%r13;                               \
    mov 96(%rsp),%r12;                                \
    add $168,%rsp;                                    \
    .cfi_def_cfa_offset 8;                            \
    ret;                                              \
    1:;                                               \
    /* Stack is not aligned according to AMD64 ABI */ \
    int $3;                                           \
    .cfi_endproc;

MAKE_VM_ENTRY_FUNC(uj_vm_prepare_call, uj_vm_call_entry)
MAKE_VM_ENTRY_FUNC(uj_vm_prepare_cpcall, uj_vm_cpcall_entry)
MAKE_VM_ENTRY_FUNC(uj_prepare_coroutine_bc_ret_z, uj_coroutine_bc_ret_z)
MAKE_VM_ENTRY_FUNC(uj_prepare_coroutine_vm_return, uj_coroutine_vm_return)
MAKE_VM_ENTRY_FUNC(uj_prepare_initial_coroutine_call, uj_initial_coroutine_call)

/* Landing pad in case an exception is caught by pcall/xpcall */
    .global uj_vm_ff_landing_pad
uj_vm_ff_landing_pad:
    /*
     * rsp will point to vm_frame structure. Frame where bytecode is executed
     * (i.e. where we need to return) is located 8 bytes below. Return address
     * will be overwritten by external unwinder, so we must restore it.
     */
    mov %rsp,%rdi
    lea -8(%rsp),%rsp /* Subtract return address */
    mov 160(%rsp),%rax /* rax = vmf->interp_ret_addr */
    mov %rax,(%rsp) /* Restore original return address */
    jmp uj_vm_unwind_ff_eh

/* Landing pad in case an exception is caught by C API */
    .global uj_vm_c_landing_pad
uj_vm_c_landing_pad:
    /* See comment in uj_vm_ff_landing_pad */
    mov %rsp,%rdi
    mov %rax,%rsi /* Return code is set to rax in dwarf_cleanup */
    lea -8(%rsp),%rsp /* Subtract return address */
    mov 160(%rsp),%rax /* rax = vmf->interp_ret_addr */
    mov %rax,(%rsp) /* Restore original return address */
    jmp uj_vm_unwind_c_eh

.section .note.GNU-stack,"",@progbits
